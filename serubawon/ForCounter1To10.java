//Question 46 for loop from 1 t0 10
// set loop variable to 1 
// set loop condition to <= 10
// set increment counter

public class ForCounter1To10 {
	public static void main(String[] args) {
	

		for (int counter = 1; counter <= 10; counter++) { 
			System.out.printf("%d%n", counter);
		
		}
		System.out.println();
	}
}

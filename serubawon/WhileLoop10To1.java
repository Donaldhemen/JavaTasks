// Question 47 while loop 10 to 1
// set loop variable to 10
// set loop condition to >= 1
// set loop increment counter ++
// print loop

public class WhileLoop10To1 {
	public static void main(String[] args) {
		int counter = 10;

		while (counter >= 1) { 
			System.out.printf("%d ", counter--);
		
		}
		System.out.println();
	}
}
// Question 54 Even numbers from 1 to 50 for loop
// set loop variable to 2
// set loop condition <= 50
// set increment += 2
// print all on one line

public class EvenNumbers1to50ForLoop {
	public static void main(String[] args) {
	

		for (int counter = 2; counter <= 50; counter+=2) { 
			
			System.out.printf("%d ", counter);
			
		}
		System.out.println();
	}
}
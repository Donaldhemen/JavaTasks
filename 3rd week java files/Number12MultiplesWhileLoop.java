 // set counter to 1
// while counter is greater than or equal to 12
// set counter * 12 in print prompt 
// set counter ++

public class Number12MultiplesWhileLoop {
    public static void main(String[] args) {

	
	int counter = 1;

		while (counter <= 12) { 
			
			System.out.printf("%d ", counter * 12);
			counter++ ;
		}
	}
}
 // set counter to 1
// while counter is greater than or equal to 20
// set counter square in print prompt 
// set counter ++ 

public class SquaresTo20 {
    public static void main(String[] args) {

	
	int counter = 1;

		while (counter <= 20) { 
			
			System.out.printf("%d ", counter * counter);
			counter++ ;
		}
	}
}
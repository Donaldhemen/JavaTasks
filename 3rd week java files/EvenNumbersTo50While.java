// set counter to 2
// while counter is greater than or equal to 50
// set counter in print prompt 
// set counter +=2

public class EvenNumbersTo50While {
    public static void main(String[] args) {

	
	int counter = 2;

		while (counter <= 50) { 
			
			System.out.printf("%d ", counter);
			counter+=2 ;
		}
	}
}
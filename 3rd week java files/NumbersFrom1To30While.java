 // set counter to 1
// while counter is greater than or equal to 30
// set counter in print prompt 
// set counter ++ 

public class NumbersFrom1To30While {
    public static void main(String[] args) {

	
	int counter = 1;

		while (counter <= 30) { 
			
			System.out.printf("%d ", counter);
			counter++ ;
		}
	}
}
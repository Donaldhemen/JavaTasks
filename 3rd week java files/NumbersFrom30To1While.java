 // set counter to 30
// while counter is less than or equal to 1
// set counter in print prompt 
// set counter --

public class NumbersFrom30To1While {
    public static void main(String[] args) {

	
	int counter = 30;

		while (counter >= 1) { 
			
			System.out.printf("%d ", counter);
			counter-- ;
		}
	}
}
// set control variable to 20
// set loop condition to greater than or equal to 1
// set counter decrement counter--
// prompt display print counter


public class Numbers20To1 {
	public static void main(String[] args) {
		

		for (int counter = 20; counter >= 1; counter--) { 
				 
			System.out.printf("%d ", counter);
				
			
		}
		System.out.println();
	}
}
// set counter to 50 
// while counter is less than or equal to 100
// set ++ counter in print prompt 
// set counter ++ 

public class OddNumbers50To100 {
    public static void main(String[] args) {
	
	int counter = 50;

		while (counter <= 99) { 
			System.out.printf("%d ", ++counter);
			++counter;
		}
	}
}
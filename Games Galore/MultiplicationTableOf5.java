// initialise loop variable to 1
// set loop condition to <= 12 and increment
//  number * counter and display

public class MultiplicationTableOf5 {
	public static void main(String[] args) {
		
		for (int counter = 1; counter <= 12; counter++) {
			System.out.printf("%n%d", counter *5);
			
		}
		System.out.println();
	}
}